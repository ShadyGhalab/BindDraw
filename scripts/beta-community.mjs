export function enhanceCommunity(html,config,catalog,keys,locale,labels,activities){
 const e=v=>String(v).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'})[c]);
 const row=catalog[locale],t=Object.fromEntries(keys.map((key,i)=>[key,e(row[i])]));
 const c=labels[locale],tasks=activities[locale];
 if(!c||c.length!==(config.kind==='ink'?12:10)||!tasks||tasks.length!==5||[...c,...tasks].some(v=>typeof v!=='string'||!v.trim())||!c[8].includes('{n}'))throw Error('Incomplete community copy: '+locale);
 const [founding,personal,groupNote,wave,why,suggest,journey,optional,day,final,play,playNote]=c.map(e);
 function replaceOnce(from,to){
   if(!html.includes(from)||html.indexOf(from)!==html.lastIndexOf(from))throw Error('Expected unique community insertion: '+from.slice(0,90));
   html=html.replace(from,to);
 }
 replaceOnce('<link rel="stylesheet" href="/beta/funnel.css">','<link rel="stylesheet" href="/beta/funnel.css"><link rel="stylesheet" href="/beta/community.css">');
 replaceOnce('<p class="eyebrow">'+t.beta+'</p>','<p class="eyebrow">'+t.beta+' · '+founding+'</p>');
 replaceOnce('<p>'+t.intro+'</p>','<p class="developer-invite">'+personal+'</p>');
 replaceOnce('<h2 id="steps-title">'+t.steps+'</h2>','<h2 id="steps-title">'+t.steps+'</h2><p class="enroll-clarity">'+groupNote+'</p>');
 const suggestion=e('mailto:'+config.email+'?subject='+encodeURIComponent(config.name+' — '+c[5]));
 const webPreview=config.kind==='ink'?'<div class="browser-preview"><div><h3>'+play+'</h3><p>'+playNote+'</p></div><a class="action" href="https://blind-draw-c6ee2.web.app/" target="_blank" rel="noopener noreferrer">'+play+'</a></div>':'';
 replaceOnce('<a class="action primary" href="#enroll">'+t.steps+'</a></section>','<a class="action primary" href="#enroll">'+t.steps+'</a>'+webPreview+'</section>');
 const community='<section class="founding-community" aria-labelledby="founding-title"><div class="founding-emblem" aria-hidden="true">✦</div><div><p class="community-kicker">'+founding+'</p><h2 id="founding-title">'+wave+'</h2><p>'+why+'</p><div class="community-actions"><a class="action primary" href="#enroll">'+t.step2+'</a><a class="action" href="'+suggestion+'">'+suggest+'</a></div></div></section>';
 replaceOnce('<section class="commit" aria-labelledby="commit-title">',community+'\n<section class="commit" aria-labelledby="commit-title">');
 const cards=[...tasks,c[9]].map((task,i)=>'<li data-activity-day="'+[1,3,5,7,10,14][i]+'"><span>'+day.replace('{n}',new Intl.NumberFormat(locale).format([1,3,5,7,10,14][i]))+'</span><p>'+e(task)+'</p></li>').join('');
 const feedback=html.match(/<a class="feedback" href="([^"]+)" data-feedback-link>/)?.[1];
 if(!feedback)throw Error('Missing established feedback link');
 const journeySection='<section class="tester-adventure" aria-labelledby="adventure-title"><h2 id="adventure-title">'+journey+'</h2><p>'+optional+'</p><ol class="adventure-grid">'+cards+'</ol><a class="action" href="'+feedback+'">'+t.feedback+'</a></section>';
 replaceOnce('<section class="reminder" data-reminder hidden aria-labelledby="reminder-title">',journeySection+'\n<section class="reminder" data-reminder hidden aria-labelledby="reminder-title">');
 return html;
}
